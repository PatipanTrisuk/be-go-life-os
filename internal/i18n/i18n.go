func T(c *gin.Context, key string) string {
	lang := "en"
	if v, ok := c.Get(middleware.LocaleKey); ok {
		if s, ok := v.(string); ok && s != "" {
			lang = s
		}
	}
	if msg, ok := messages[lang][key]; ok {
		return msg
	}
	return messages["en"][key]
}
